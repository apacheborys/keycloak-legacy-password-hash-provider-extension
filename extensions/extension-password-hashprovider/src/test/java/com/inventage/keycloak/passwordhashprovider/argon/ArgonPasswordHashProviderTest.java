package com.inventage.keycloak.passwordhashprovider.argon;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.keycloak.models.credential.PasswordCredentialModel;

import java.util.List;

class ArgonPasswordHashProviderTest {

    private static ArgonPasswordHashProvider argonPasswordHashProvider;

    @BeforeAll
    static void init_argon_provider() {
        ArgonPasswordHashProviderFactory argonFactory = new ArgonPasswordHashProviderFactory();
        argonPasswordHashProvider = (ArgonPasswordHashProvider) argonFactory.create(null);
    }

    @Test
    final void valid_argon2i_hashes() {
        //given
        final List<String> argonHashes = List.of("$argon2i$v=19$m=65536,t=16,p=1$bnI2SEl3UXNicmovRTZYdg$MeU+vEnpIQb1q1QiWNiIq70K8hoWWb3gbp1CfqH6jAU",
                "$argon2i$v=19$m=16,t=2,p=1$SG5lU1J6bVQwQVdqWnJVVg$D4lhpKP+NECizhGS+9uZiA",
                "$argon2i$v=19$m=65536,t=2,p=1$TG16SkpPTkVwZm9XM2dKQg$+aI4J6tS+V6fwILXuDieQA",
                "$argon2i$v=19$m=65536,t=2,p=8$Z1hRNTA1UDV2MW8xOFF2eQ$p2+OOn15Aez9qMlPqrmAYw");
        final List<String> passwords = List.of(
                "sozialinfo",
                "password123",
                "qwertyuiop",
                "letmein");
        for (int i = 0; i < argonHashes.size(); i++){
            final String argonHash = argonHashes.get(i);
            final String password = passwords.get(i);
            //when
            final boolean passwordMatches = argonPasswordHashProvider.verifyArgonPassword(password, argonHash);
            //then
            Assertions.assertTrue(passwordMatches, "Password " + password + " does not match " + argonHash);
        }
    }

    @Test
    final void invalid_argon2i_hashes() {
        //given
        final List<String> argonHashes = List.of("$argon2i$v=19$m=65536,t=16,p=1$bnI2SEl3UXNicmovRTZYdg$MeU+vEnpIQb1q1QiWNiIq70K8hoWWb3gbp1CfqH6jAU",
                "$argon2i$v=19$m=16,t=2,p=1$SG5lU1J6bVQwQVdqWnJVVg$D4lhpKP+NECizhGS+9uZiA",
                "$argon2i$v=19$m=65536,t=2,p=1$TG16SkpPTkVwZm9XM2dKQg$+aI4J6tS+V6fwILXuDieQA",
                "$argon2i$v=19$m=65536,t=2,p=8$Z1hRNTA1UDV2MW8xOFF2eQ$p2+OOn15Aez9qMlPqrmAYw");
        final List<String> passwords = List.of(
                "invalid-sozialinfo",
                "invalid-password123",
                "invalid-qwertyuiop",
                "invalid-letmein");
        for (int i = 0; i < argonHashes.size(); i++){
            final String argonHash = argonHashes.get(i);
            final String password = passwords.get(i);
            //when
            final boolean passwordMatches = argonPasswordHashProvider.verifyArgonPassword(password, argonHash);
            //then
            Assertions.assertFalse(passwordMatches, "Password " + password + " should not match " + argonHash);
        }
    }

    @Test
    final void valid_argon2id_hash_from_php_password_hash() {
        final String argon2idHash = "$argon2id$v=19$m=65536,t=4,p=1$L0lWVkk4aS41bEg2VFp5Mg$nqhhieV5XW3dr5iTbf3fvpv0bO7/6bEMw2VGSAYMijg";
        Assertions.assertTrue(
                argonPasswordHashProvider.verifyArgonPassword("Symf0ny!Pass123", argon2idHash),
                "Argon2id hash generated by PHP password_hash should be verified");
    }

    @Test
    final void malformed_or_empty_hashes_do_not_throw_and_return_false() {
        Assertions.assertFalse(argonPasswordHashProvider.verifyArgonPassword("password", "not-a-valid-argon-hash"));
        Assertions.assertFalse(argonPasswordHashProvider.verifyArgonPassword("password", ""));
        Assertions.assertFalse(argonPasswordHashProvider.verifyArgonPassword("password", null));
        Assertions.assertFalse(argonPasswordHashProvider.verifyArgonPassword(null, "$argon2id$v=19$m=65536,t=4,p=1$salt$hash"));
    }

    @Test
    final void argon_alias_factories_verify_passwords() {
        final String argon2idHash = "$argon2id$v=19$m=65536,t=4,p=1$L0lWVkk4aS41bEg2VFp5Mg$nqhhieV5XW3dr5iTbf3fvpv0bO7/6bEMw2VGSAYMijg";

        final List<AbstractArgonPasswordHashProviderFactory> factories = List.of(
                new ArgonPasswordHashProviderFactory(),
                new Argon2PasswordHashProviderFactory(),
                new Argon2iPasswordHashProviderFactory(),
                new Argon2idPasswordHashProviderFactory()
        );

        for (AbstractArgonPasswordHashProviderFactory factory : factories) {
            final PasswordCredentialModel credential = PasswordCredentialModel.createFromValues(
                    factory.getId(),
                    null,
                    1,
                    argon2idHash
            );
            final ArgonPasswordHashProvider provider = (ArgonPasswordHashProvider) factory.create(null);
            Assertions.assertTrue(
                    provider.verify("Symf0ny!Pass123", credential),
                    "Provider " + factory.getId() + " must verify valid Argon2id hashes");
        }
    }

}
